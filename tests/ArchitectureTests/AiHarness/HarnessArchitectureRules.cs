    private static void NamingRules(Context c)
    {
        // naming-identity: the candidate record is exactly the pinned NuGet identity, centrally pinned and locked as a build-only reference.
        const string candidateFile = "eng/policy/naming-candidate.json";
        var candidate = Obj(ParseJson(c.Text(candidateFile)));
        if (candidate is null)
        {
            c.Report("naming-identity", candidateFile, "The naming candidate record is missing or malformed");
        }
        else
        {
            var expectedKeys = new[] { "archiveSha512", "assets", "ecosystem", "package", "publication", "sourceCommit", "version" };
            if (!candidate.Select(entry => entry.Key).Order(StringComparer.Ordinal).SequenceEqual(expectedKeys, StringComparer.Ordinal))
            {
                c.Report("naming-identity", candidateFile, "Candidate record must have exactly package, ecosystem, version, sourceCommit, archiveSha512, publication and assets");
            }

            if (Str(candidate["package"]) != NamingCandidate.PackageId) c.Report("naming-identity", candidateFile, "Unexpected producer package");
            if (Str(candidate["ecosystem"]) != "nuget") c.Report("naming-identity", candidateFile, "The producer ecosystem is not NuGet");
            if (Str(candidate["version"]) != NamingCandidate.Version) c.Report("naming-identity", candidateFile, "The candidate is not the pinned version");
            if (Str(candidate["sourceCommit"]) is not { } commit || !CommitHex.IsMatch(commit) || commit != NamingCandidate.SourceCommit)
            {
                c.Report("naming-identity", candidateFile, "The producer source commit is not the pinned full SHA");
            }

            if (Str(candidate["archiveSha512"]) != NamingCandidate.ArchiveSha512) c.Report("naming-identity", candidateFile, "The archive SHA512 is not the pinned digest");
            if (Str(candidate["publication"]) is not { } publication || !NamingPublication.IsMatch(publication))
            {
                c.Report("naming-identity", candidateFile, "Publication receipt must be an ArcForges/Contracts workflow run");
            }

            var assets = Obj(candidate["assets"]);
            var assetKeys = assets?.Select(entry => entry.Key).Order(StringComparer.Ordinal).ToArray() ?? [];
            if (!assetKeys.SequenceEqual(new[] { NamingCandidate.ScannerPath, NamingCandidate.PolicyPath }, StringComparer.Ordinal))
            {
                c.Report("naming-identity", candidateFile, "Asset set must be exactly the published scanner and policy");
            }

            if (Str(assets?[NamingCandidate.ScannerPath]) != NamingCandidate.ScannerSha256 || Str(assets?[NamingCandidate.PolicyPath]) != NamingCandidate.PolicySha256)
            {
                c.Report("naming-identity", candidateFile, "The candidate asset digests are not the pinned SHA256 values");
            }
        }

        if (c.CentralPackages().GetValueOrDefault(NamingCandidate.PackageId) != NamingCandidate.Version)
        {
            c.Report("naming-identity", "Directory.Packages.props", "The naming candidate is not centrally pinned at the exact version");
        }

        var architecture = c.Projects.GetValueOrDefault("tests/ArchitectureTests/ArcForges.Cloud.ArchitectureTests.csproj");
        if (architecture is null || !architecture.PackageReferences.Any(p => p.Id == NamingCandidate.PackageId && p.PrivateAssets))
        {
            c.Report("naming-identity", "tests/ArchitectureTests/ArcForges.Cloud.ArchitectureTests.csproj", "The naming candidate is not a build-only reference of the architecture host");
        }

        // naming-scan: the checkout's scan report passed for Cloud under the pinned policy with zero findings.
        var reportText = c.Text(NamingReport);
        if (reportText is null)
        {
            c.Report("naming-scan", NamingReport, "The naming scan report is missing; run the policy gate first");
            return;
        }

        var report = Obj(ParseJson(reportText));
        var rows = (report?["repositories"] as JsonArray)?.Select(row => Obj(row)).OfType<JsonObject>().Where(row => Str(row["repository"]) == "Cloud").ToList() ?? [];
        if (rows.Count != 1 || Str(rows[0]["status"]) != "pass" || (rows[0]["findings"] as JsonArray)?.Count != 0)
        {
            c.Report("naming-scan", NamingReport, "The naming scan of Cloud did not pass with zero findings");
        }

        if (Str(report?["policySha256"]) != NamingCandidate.PolicySha256)
        {
            c.Report("naming-scan", NamingReport, "The scan ran under another policy");
        }
    }

    // ---------------------------------------------------------------- WP-05.03 wire

    private static void WireRules(Context c)
    {
        // wire-package: every runtime Contracts package shares one exact version (the naming tool is build-only and excluded).
        var contracts = c.CentralPackages().Where(p => p.Key.StartsWith("ArcForges.Contracts.", StringComparison.Ordinal) && p.Key != NamingCandidate.PackageId)
            .Select(p => p.Value).Distinct(StringComparer.Ordinal).ToList();
        if (contracts.Count > 1)
        {
            c.Report("wire-package", "Directory.Packages.props", "Contracts runtime packages come from more than one version");
        }

        WirePackagePin(c);

        // wire-import: a project compiles only its own files.
        foreach (var project in c.Projects.Values)
        {
            var folder = project.Path[..project.Path.LastIndexOf('/')] + "/";
            foreach (var include in project.CompileIncludes)
            {
                var target = Project.Normalize(project.Path, include);
                if (target is null || !target.StartsWith(folder, StringComparison.Ordinal))
                {
                    c.Report("wire-import", project.Path, "Compiles a file outside its project folder: " + include);
                }
            }
        }

        // wire-source: no copied generated source or schema file is authored in this repository; protoc output is not authored here.
        foreach (var path in c.Sources.Keys.Order(StringComparer.Ordinal))
        {
            if (ProtoSchemaFile.IsMatch(path))
            {
                c.Report("wire-source", path, "Authored schema or copied generated wire source");
            }

            if (IsCodeFile(path) && !DeclarationFile().IsMatch(path) && !path.StartsWith("tests/ArchitectureTests/", StringComparison.Ordinal)
                && !path.StartsWith("eng/policy/", StringComparison.Ordinal) && ProtocHeader.IsMatch(c.Sources[path]))
            {
                c.Report("wire-source", path, "Generated protocol buffer output authored in this repository");
            }
        }

        // wire-codec: no handwritten or alternative wire codec in production C#.
        foreach (var (file, tree) in c.ProductionCSharp)
        {
            foreach (var token in tree.GetRoot().DescendantTokens().Where(t => t.IsKind(SyntaxKind.IdentifierToken) && WireCodecNames.Contains(t.ValueText, StringComparer.Ordinal)))
            {
                c.Report("wire-codec", file, "Handwritten wire codec primitive: " + token.ValueText);
            }
        }

        // wire-schema: production C# does not implement the generated message contract itself.
        foreach (var (file, tree) in c.ProductionCSharp)
        {
            foreach (var declaration in tree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
            {
                if (declaration.BaseList is { } list && list.Types.Any(t => t.ToString().Contains("IMessage", StringComparison.Ordinal)))
                {
                    c.Report("wire-schema", file, "Handwritten message implements the generated contract: " + declaration.Identifier.ValueText);
                }
            }
        }

        // wire-shadow: no production declaration sits in a generated Contracts namespace.
        foreach (var (file, tree) in c.ProductionCSharp)
        {
            foreach (var name in tree.GetRoot().DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().Select(n => n.Name.ToString()))
            {
                if (name == "ArcForges.Contracts" || name.StartsWith("ArcForges.Contracts.", StringComparison.Ordinal))
                {
                    c.Report("wire-shadow", file, "Declares a type in the generated namespace " + name);
                }
            }
        }
    }

    /// <summary>
    /// The wire package pin (CLOUD.84 S38(1)). If the root manifest declares the public wire package, in either section, the declaration is
    /// one exact, registry-locked candidate that the lock carries too. A release Worker file that imports it needs it as a runtime
    /// dependency; a build or test consumer may hold it as a development dependency. If the package is neither declared nor imported, the
    /// rule has nothing to pin and passes. Every declared or imported use stays refused unless it meets these conditions.
    /// </summary>
    private static void WirePackagePin(Context c)
    {
        var root = Obj(ParseJson(c.Text("package.json")));
        var lockFile = Obj(ParseJson(c.Text("package-lock.json")));
        var runtime = StringMap(root?["dependencies"]).GetValueOrDefault(PublicWirePackage);
        var pin = runtime ?? StringMap(root?["devDependencies"]).GetValueOrDefault(PublicWirePackage);
        var declared = runtime is not null || StringMap(root?["devDependencies"]).ContainsKey(PublicWirePackage);
        var imported = new List<string>();
        foreach (var file in c.TypeScript.Where(file => file.Release))
        {
            if (file.References.Any(reference => reference.Specifier is not null && (reference.Specifier == PublicWirePackage || reference.Specifier.StartsWith(PublicWirePackage + "/", StringComparison.Ordinal))))
                imported.Add(file.Path);
        }

        if (declared)
        {
            var entry = Obj(Obj(lockFile?["packages"])?["node_modules/" + PublicWirePackage]);
            var tarball = "https://registry.npmjs.org/" + PublicWirePackage + "/-/proto-" + pin + ".tgz";
            var lockRoot = Obj(Obj(lockFile?["packages"])?[""]);
            var lockedPin = StringMap(lockRoot?["dependencies"]).GetValueOrDefault(PublicWirePackage) ?? StringMap(lockRoot?["devDependencies"]).GetValueOrDefault(PublicWirePackage);
            var integrity = Str(entry?["integrity"]) ?? string.Empty;
            var integrityOk = integrity.StartsWith("sha512-", StringComparison.Ordinal) && Sha512Base64.IsMatch(integrity["sha512-".Length..]);
            if (pin is null || !ExactVersion.IsMatch(pin) || !pin.Contains("-ci.", StringComparison.Ordinal) || Str(entry?["version"]) != pin
                || Str(entry?["resolved"]) != tarball || !integrityOk || lockedPin != pin)
            {
                c.Report("wire-package", "package.json", "Exact registry-locked published candidate pin of the public wire package required");
            }
        }

        foreach (var path in imported)
        {
            if (runtime is null)
                c.Report("wire-package", path, "Worker imports the wire package without a runtime dependency");
        }
    }

    // ---------------------------------------------------------------- WP-05.04 banned and the Worker token rules

    private static void BannedRules(Context c)
    {
        foreach (var (file, tree) in c.ProductionCSharp)
        {
            var root = tree.GetRoot();

            // banned-reflection: no reflection emit, dynamic loading or reflective construction.
            foreach (var use in root.DescendantNodes().OfType<UsingDirectiveSyntax>().Where(u => u.Name?.ToString().StartsWith("System.Reflection.Emit", StringComparison.Ordinal) == true))
            {
                c.Report("banned-reflection", file, "Reflection emit namespace");
            }

            foreach (var invocation in root.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                var text = invocation.Expression.ToString();
                if (ReflectionCall.IsMatch(text)) c.Report("banned-reflection", file, "Reflective call: " + text);
                if (text.EndsWith("Expression.Compile", StringComparison.Ordinal) || text.EndsWith("CSharpScript.EvaluateAsync", StringComparison.Ordinal))
                {
                    c.Report("banned-dynamic-code", file, "Runtime compilation: " + text);
                }

                // banned-blocking-wait: no sync-over-async wait or sync host call.
                if (text.EndsWith(".Wait", StringComparison.Ordinal) || text.EndsWith("GetAwaiter().GetResult", StringComparison.Ordinal) || text.EndsWith(".GetResult", StringComparison.Ordinal))
                {
                    c.Report("banned-blocking-wait", file, "Blocking wait: " + text);
                }

                // banned-secret-logging: no logging of a secret-bearing or content-bearing value.
                if (LoggingCall.IsMatch(text) && invocation.ArgumentList.DescendantTokens().Any(t => t.IsKind(SyntaxKind.IdentifierToken) && SensitiveName.IsMatch(t.ValueText)))
                {
                    c.Report("banned-secret-logging", file, "Logs a sensitive value through " + text);
                }

                // banned-raw-memory: no unmanaged memory helpers.
                if (text.Contains("Marshal.AllocHGlobal", StringComparison.Ordinal) || text.Contains("NativeMemory.", StringComparison.Ordinal))
                {
                    c.Report("banned-raw-memory", file, "Unmanaged memory: " + text);
                }
            }

            // A task result read is a blocking wait; a stored receipt named Result is not (a syntactic heuristic, a named limit).
            foreach (var member in root.DescendantNodes().OfType<MemberAccessExpressionSyntax>().Where(m => m.Name.Identifier.ValueText == "Result" && IsTaskLike(m.Expression)))
            {
                c.Report("banned-blocking-wait", file, "Blocking task result: " + member);
            }

            foreach (var identifier in root.DescendantTokens().Where(t => t.IsKind(SyntaxKind.IdentifierToken) && t.ValueText == "dynamic"))
            {
                c.Report("banned-dynamic-code", file, "Dynamic type at line " + (identifier.GetLocation().GetLineSpan().StartLinePosition.Line + 1));
            }

            // Pinned memory is raw memory; stackalloc yields a managed Span and is not raw memory.
            foreach (var node in root.DescendantNodes().Where(n => n.IsKind(SyntaxKind.FixedStatement)))
            {
                c.Report("banned-raw-memory", file, "Pinned memory: " + node.Kind());
            }

            foreach (var token in root.DescendantTokens().Where(t => t.IsKind(SyntaxKind.UnsafeKeyword)))
            {
                c.Report("banned-raw-memory", file, "Unsafe code at line " + (token.GetLocation().GetLineSpan().StartLinePosition.Line + 1));
            }

            foreach (var use in root.DescendantNodes().OfType<UsingDirectiveSyntax>().Where(u => ProviderNamespaces.Any(p => u.Name?.ToString().StartsWith(p, StringComparison.Ordinal) == true)))
            {
                c.Report("banned-provider-sdk", file, "Provider namespace: " + use.Name);
            }

            foreach (var literal in root.DescendantTokens().Where(t => t.IsKind(SyntaxKind.StringLiteralToken)).Where(t => ProviderHost.IsMatch(t.ValueText)))
            {
                c.Report("banned-provider-sdk", file, "Direct provider endpoint in source");
            }

            // banned-float-money: production C# declares money values in decimal only.
            foreach (var declaration in root.DescendantNodes().OfType<VariableDeclarationSyntax>().Where(d => IsFloating(d.Type)))
            {
                foreach (var variable in declaration.Variables.Where(v => IsMoney(v.Identifier.ValueText)))
                {
                    c.Report("banned-float-money", file, "Floating money value: " + variable.Identifier.ValueText);
                }
            }

            foreach (var parameter in root.DescendantNodes().OfType<ParameterSyntax>().Where(p => p.Type is not null && IsFloating(p.Type) && IsMoney(p.Identifier.ValueText)))
            {
                c.Report("banned-float-money", file, "Floating money parameter: " + parameter.Identifier.ValueText);
            }

            foreach (var property in root.DescendantNodes().OfType<PropertyDeclarationSyntax>().Where(p => IsFloating(p.Type) && IsMoney(p.Identifier.ValueText)))
            {
                c.Report("banned-float-money", file, "Floating money property: " + property.Identifier.ValueText);
            }
        }

        foreach (var project in c.Projects.Values.Where(p => p.Path.StartsWith("src/", StringComparison.Ordinal)))
        {
            foreach (var package in project.PackageReferences.Where(p => ProviderNuget.IsMatch(p.Id)))
            {
                c.Report("banned-provider-sdk", project.Path, "Provider SDK package: " + package.Id);
            }
        }
    }

    /// <summary>
    /// The Worker token rules: the AI policy's per-file rules over the lexer's tokens, applied to every TypeScript file. The banned-API rules
    /// (dynamic code, reflection, waits, raw memory, provider calls, logging and money) are release-only, as in the AI policy; the adapter
    /// store rule applies to the adapter folders.
    /// </summary>
    private static void TypeScriptTokenRules(Context c, HarnessAuditOptions options)
    {
        var generated = options.GeneratedTypeScriptNames ?? new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in c.TypeScript)
        {
            var release = file.Release;
            var tokens = file.Tokens;
            var bound = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var reference in file.References.Where(r => r.Specifier is not null))
            {
                foreach (var (local, _) in reference.Bindings) bound[local] = PackageName(reference.Specifier!);
                var specifier = reference.Specifier!;
                if (specifier.StartsWith(PublicWirePackage + "/", StringComparison.Ordinal) || NodeModulesWire().IsMatch(specifier))
                {
                    c.Report("wire-import", file.Path, "Generated types must come from the package root: " + specifier);
                }

                if (BuildOutputImport().IsMatch(specifier))
                {
                    c.Report("wire-import", file.Path, "Generated build output import: " + specifier);
                }

                if (WireCodecPackage.IsMatch(specifier)) c.Report("wire-codec", file.Path, "Handwritten or alternative wire codec: " + specifier);
                if (ProviderPackage.IsMatch(specifier)) c.Report("banned-provider-sdk", file.Path, "Provider SDK import: " + specifier);
            }

            var hex = new HashSet<string>(tokens.Where(t => t.Kind == TokenKind.Number).Select(t => t.Value.ToLowerInvariant().Replace("_", string.Empty, StringComparison.Ordinal)), StringComparer.Ordinal);
            var names = new HashSet<string>(tokens.Where(t => t.Kind == TokenKind.Word).Select(t => t.Value), StringComparer.Ordinal);
            // Build tooling may read the protobuf runtime's licence header; the codec rule concerns authored product and test code.
            if (!file.Path.StartsWith("eng/", StringComparison.Ordinal)
                && (new[] { "BinaryWriter", "BinaryReader", "varint" }.Any(names.Contains) || (hex.Contains("0x7f") && hex.Contains("0x80"))))
            {
                c.Report("wire-codec", file.Path, "Manual varint or binary reader/writer logic");
            }

            for (var index = 0; index < tokens.Count; index++)
            {
                var token = tokens[index];
                var next = Peek(tokens, index + 1);
                var before = Peek(tokens, index - 1);
                if (token.Kind is TokenKind.String or TokenKind.Template)
                {
                    if (release && ProviderHost.IsMatch(token.Value)) c.Report("banned-provider-sdk", file.Path, "Direct provider endpoint literal");
                    continue;
                }

                if (token.Kind != TokenKind.Word) continue;
                var afterDot = before?.Kind == TokenKind.Punct && before.Value is "." or "?.";
                if (generated.Contains(token.Value) && GeneratedSuffix.IsMatch(token.Value) && !afterDot && before?.Kind == TokenKind.Word
                    && before.Value is "interface" or "type" or "class" or "enum" or "const" or "let" or "var" or "function")
                {
                    c.Report("wire-shadow", file.Path, "Local declaration redefines generated type " + token.Value);
                }

                if (CodecFunctions.Contains(token.Value, StringComparer.Ordinal) && next?.Value == "(" && !afterDot)
                {
                    var first = Peek(tokens, index + 2);
                    if (bound.GetValueOrDefault(token.Value) == "@bufbuild/protobuf"
                        && (first?.Kind != TokenKind.Word || bound.GetValueOrDefault(first.Value) != PublicWirePackage))
                    {
                        c.Report("wire-schema", file.Path, token.Value + " must take a generated schema imported from " + PublicWirePackage);
                    }
                }

                if (!release) continue;
                var call = next?.Value == "(";
                if (token.Value == "Reflect" && next?.Value == ".") c.Report("banned-reflection", file.Path, "Reflect entry point");
                if (token.Value is "__proto__" or "setPrototypeOf") c.Report("banned-reflection", file.Path, token.Value);
                if (token.Value == "constructor" && next?.Value == "." && Peek(tokens, index + 2)?.Value == "constructor")
                {
                    c.Report("banned-reflection", file.Path, "constructor.constructor");
                }

                if (token.Value == "eval" && call && !afterDot) c.Report("banned-dynamic-code", file.Path, "eval");
                if (token.Value == "Function" && (call || before?.Value == "new") && !afterDot) c.Report("banned-dynamic-code", file.Path, "Function constructor");
                if (token.Value is "setTimeout" or "setInterval" && call && Peek(tokens, index + 2) is { Kind: TokenKind.String or TokenKind.Template })
                {
                    c.Report("banned-dynamic-code", file.Path, token.Value + " with a code string");
                }

                if (token.Value == "importScripts" && call) c.Report("banned-dynamic-code", file.Path, "importScripts");
                if (token.Value == "WebAssembly" && next?.Value == ".")
                {
                    var member = Peek(tokens, index + 2)?.Value ?? string.Empty;
                    if (member == "Memory") c.Report("banned-raw-memory", file.Path, "WebAssembly.Memory");
                    else c.Report("banned-dynamic-code", file.Path, "WebAssembly." + member);
                }

                if (token.Value == "SharedArrayBuffer") c.Report("banned-raw-memory", file.Path, "SharedArrayBuffer");
                if (token.Value == "Atomics" && next?.Value == ".")
                {
                    var member = Peek(tokens, index + 2)?.Value ?? string.Empty;
                    if (member == "wait") c.Report("banned-blocking-wait", file.Path, "Atomics.wait");
                    else c.Report("banned-raw-memory", file.Path, "Atomics." + member);
                }

                if (token.Value.EndsWith("Sync", StringComparison.Ordinal) && call && afterDot)
                {
                    c.Report("banned-blocking-wait", file.Path, "Synchronous host call " + token.Value);
                }

                if (token.Value == "while" && ClockBusyWait(tokens, index)) c.Report("banned-blocking-wait", file.Path, "Busy-wait on the clock");
                if (token.Value == "XMLHttpRequest") c.Report("banned-blocking-wait", file.Path, "XMLHttpRequest");

                if (IsAdapter(file.Path))
                {
                    if (AdapterStoreTypes.Contains(token.Value, StringComparer.Ordinal) && !afterDot)
                    {
                        c.Report("layer-business-authority", file.Path, "Cloud-owned business store type " + token.Value);
                    }

                    if (DurableObjectTypes.Contains(token.Value, StringComparer.Ordinal) && !afterDot && file.Path != AlarmFile)
                    {
                        c.Report("layer-business-authority", file.Path, "Durable Object lifecycle is held only by the run alarm");
                    }
                }

                if (token.Value == "AI" && afterDot && file.Path != WorkerEntry && !file.Path.StartsWith(AdapterFolder, StringComparison.Ordinal))
                {
                    c.Report("banned-provider-call", file.Path, "Inference binding referenced outside the entry/adapter");
                }

                if (token.Value == "run" && call && afterDot && before is not null && Peek(tokens, index - 2)?.Value is "ai" or "AI"
                    && !file.Path.StartsWith(AdapterFolder, StringComparison.Ordinal))
                {
                    c.Report("banned-provider-call", file.Path, "Inference binding called outside the model adapter");
                }

                if (token.Value == "console" && next?.Value == "." && Peek(tokens, index + 3)?.Value == "(")
                {
                    foreach (var argument in CallArguments(tokens, index + 3))
                    {
                        if (argument.Kind == TokenKind.Word && SensitiveName.IsMatch(argument.Value))
                        {
                            c.Report("banned-secret-logging", file.Path, "console." + (Peek(tokens, index + 2)?.Value ?? string.Empty) + " receives " + argument.Value);
                        }
                    }
                }

                if (IdentifierParts(token.Value).Any(part => MoneyParts.Contains(part, StringComparer.Ordinal)) && FloatingMoney(tokens, index))
                {
                    c.Report("banned-float-money", file.Path, "Floating-point handling near " + token.Value);
                }
            }
        }
    }

