                    }
                }
            }
        }
    }

    /// <summary>The Worker import graph: unadmitted and absolute references, sibling escapes, entry imports, cycles and runtime dependencies.</summary>
    private static void WorkerImportGraph(Context c)
    {
        var runtime = RuntimeDependencies(c);
        var edges = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var file in c.TypeScript)
        {
            var targets = new List<string>();
            foreach (var reference in file.References)
            {
                var specifier = reference.Specifier;
                if (specifier is null)
                {
                    c.Report(file.Release ? "banned-dynamic-code" : "layer-escape", file.Path, "Computed " + FormName(reference) + " specifier needs explicit admission");
                    continue;
                }

                if (specifier.StartsWith("@arcforges/", StringComparison.Ordinal) && !AdmittedPackages.Contains(specifier) && !specifier.StartsWith(PublicWirePackage + "/", StringComparison.Ordinal))
                {
                    c.Report("layer-product-reference", file.Path, "Unadmitted ArcForges import: " + specifier);
                }

                if (ExternalSpecifier.IsMatch(specifier))
                {
                    c.Report("layer-escape", file.Path, "External or absolute import: " + specifier);
                }

                if (specifier.StartsWith('.'))
                {
                    var (escaped, resolved) = ResolveLocal(file.Path, specifier, c.Sources);
                    if (escaped)
                    {
                        c.Report("layer-escape", file.Path, "Sibling or parent checkout import: " + specifier);
                    }
                    else if (resolved is null && !UnresolvedAllowed.IsMatch(specifier))
                    {
                        c.Report("layer-escape", file.Path, "Unresolved local import: " + specifier);
                    }
                    else if (resolved is not null)
                    {
                        targets.Add(resolved);
                        if (file.Release && !IsRelease(resolved))
                        {
                            c.Report("layer-escape", file.Path, "Worker source reaches " + resolved);
                        }

                        if (resolved == WorkerEntry && file.Path != WorkerEntry)
                        {
                            c.Report("layer-entry", file.Path, "Imports the Worker entry: " + specifier);
                        }
                    }

                    continue;
                }

                if (!file.Release) continue;
                if (specifier.StartsWith("node:", StringComparison.Ordinal))
                {
                    c.Report("layer-runtime-dependency", file.Path, "Node built-in in the Worker path: " + specifier);
                }
                else if (specifier.StartsWith("cloudflare:", StringComparison.Ordinal))
                {
                    continue;
                }
                else if (!runtime.Contains(PackageName(specifier)))
                {
                    c.Report("layer-runtime-dependency", file.Path, "Not a declared runtime dependency: " + PackageName(specifier));
                }
            }

            edges[file.Path] = targets;
        }

        // layer-cycle: the release files form an acyclic import graph.
        var visiting = new HashSet<string>(StringComparer.Ordinal);
        var done = new HashSet<string>(StringComparer.Ordinal);
        void Walk(string file, List<string> stack)
        {
            if (done.Contains(file)) return;
            if (visiting.Contains(file))
            {
                var start = stack.IndexOf(file);
                c.Report("layer-cycle", file, "Import cycle: " + string.Join(" -> ", stack.Skip(start).Append(file)));
                return;
            }

            visiting.Add(file);
            foreach (var next in edges.GetValueOrDefault(file) ?? [])
            {
                if (IsRelease(next)) Walk(next, [.. stack, file]);
            }

            visiting.Remove(file);
            done.Add(file);
        }

        foreach (var file in edges.Keys.Where(IsRelease).Order(StringComparer.Ordinal))
        {
            Walk(file, []);
        }
    }

    /// <summary>
    /// The Worker configuration: no workers.dev or preview exposure, no route that exposes an internal path, and no store binding reachable
    /// from an adapter. Each environment is checked as well as the top level, so an environment cannot re-enable exposure.
    /// </summary>
    private static void WorkerConfiguration(Context c)
    {
        var wrangler = Obj(ParseJson(c.Text("wrangler.json")));
        if (wrangler is null)
        {
            c.Report("layer-public-exposure", "wrangler.json", "Worker configuration is missing");
            return;
        }

        var environments = new List<(string Name, JsonObject Object)> { ("top", wrangler) };
        if (Obj(wrangler["env"]) is { } env)
        {
            environments.AddRange(env.Where(entry => Obj(entry.Value) is not null).Select(entry => ("env." + entry.Key, Obj(entry.Value)!)));
        }

        var storeBindings = new List<string>();
        foreach (var (name, element) in environments)
        {
            var prefix = name == "top" ? string.Empty : name + " ";
            if (!IsFalse(element["workers_dev"]) && (name == "top" || element.ContainsKey("workers_dev")))
            {
                c.Report("layer-public-exposure", "wrangler.json", prefix + "workers_dev must be false");
            }

            if (!IsFalse(element["preview_urls"]) && (name == "top" || element.ContainsKey("preview_urls")))
            {
                c.Report("layer-public-exposure", "wrangler.json", prefix + "preview_urls must be false");
            }

            foreach (var key in new[] { "routes", "route" })
            {
                foreach (var pattern in RoutePatterns(element[key]))
                {
                    if (ExposesInternalPath(pattern))
                    {
                        c.Report("layer-public-exposure", "wrangler.json", prefix + "route exposes an internal path: " + pattern);
                    }
                }
            }

            foreach (var kind in StoreKinds)
            {
                if (element[kind] is JsonArray list)
                {
                    storeBindings.AddRange(list.Select(item => Str(Obj(item)?["binding"])).OfType<string>());
                }
            }

            if (Obj(element["queues"]) is { } queues && queues["producers"] is JsonArray producers)
            {
                storeBindings.AddRange(producers.Select(item => Str(Obj(item)?["binding"])).OfType<string>());
            }
        }

        foreach (var file in c.TypeScript.Where(file => IsAdapter(file.Path)))
        {
            foreach (var binding in storeBindings.Distinct(StringComparer.Ordinal))
            {
                if (file.Tokens.Any(token => token.Kind == TokenKind.Word && token.Value == binding))
                {
                    c.Report("layer-business-authority", file.Path, "Adapter reaches store binding " + binding);
                }
            }
        }
    }

    private static IEnumerable<string> RoutePatterns(JsonNode? node) => node switch
    {
        JsonArray list => list.Select(item => Str(item) ?? Str(Obj(item)?["pattern"])).OfType<string>(),
        JsonValue => [Str(node)!],
        _ => [],
    };

    /// <summary>A route exposes an internal path when its path begins with /internal or is a catch-all that covers every path.</summary>
    private static bool ExposesInternalPath(string pattern)
    {
        var slash = pattern.IndexOf('/', StringComparison.Ordinal);
        if (slash < 0) return false;
        var path = pattern[slash..];
        return path.StartsWith("/internal", StringComparison.Ordinal) || path == "/*";
    }

    private static string FormName(ModuleReference reference) => reference.Form switch
    {
        ModuleForm.Dynamic => "dynamic",
        ModuleForm.Require => "require",
        ModuleForm.Export => "export",
        _ => "import",
    };

    /// <summary>The Worker adapter folders: the Workers AI adapter and the Harness wake handle.</summary>
    private static bool IsAdapter(string path) => path.StartsWith(AdapterFolder, StringComparison.Ordinal) || path.StartsWith(HarnessFolder, StringComparison.Ordinal);

    private static IEnumerable<string> ManifestPaths(Context c) =>
        c.Sources.Keys.Where(path => path == "package.json" || path.EndsWith("/package.json", StringComparison.Ordinal)).Order(StringComparer.Ordinal);

