    /// <summary>The manifests: an SPDX identifier, an enumerated boundary, the inventory, the Apache set and the cross-boundary references.</summary>
    private static void ManifestLicences(Context c)
    {
        var inventoryText = c.Text("eng/policy/licence-boundary.json");
        var inventory = Obj(ParseJson(inventoryText));
        var rows = (inventory?["projects"] as JsonArray)?.Select(row => Obj(row)).OfType<JsonObject>().ToList() ?? [];
        var manifests = ManifestPaths(c).ToList();
        var projectNames = new Dictionary<string, string>(StringComparer.Ordinal);
        var boundaries = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var file in manifests)
        {
            var manifest = Obj(ParseJson(c.Text(file))) ?? new JsonObject();
            var boundary = Str(Obj(manifest["arcforges"])?["licenceBoundary"]);
            var license = Str(manifest["license"]);
            if (Str(manifest["name"]) is { } name) projectNames[name] = file;
            if (boundary is not null) boundaries[file] = boundary;
            if (license is null || !LicenceIdentifier.IsMatch(license)) c.Report("licence-declaration", file, "SPDX licence identifier is missing");
            if (boundary is not (AgplBoundary or ApacheBoundary)) c.Report("licence-declaration", file, "Licence boundary is missing or unknown");
            if (boundary == AgplBoundary && license != "AGPL-3.0-only") c.Report("licence-boundary-set", file, "AGPL boundary requires AGPL-3.0-only");
            if (boundary == ApacheBoundary && license != "Apache-2.0") c.Report("licence-boundary-set", file, "Apache boundary requires Apache-2.0");
        }

        var npmRows = rows.Where(row => Str(row["kind"]) == "npm").Select(row => Str(row["path"]) ?? string.Empty).Order(StringComparer.Ordinal).ToList();
        if (!npmRows.SequenceEqual(manifests, StringComparer.Ordinal) || inventory?["licenceBoundary"] is null)
        {
            c.Report("licence-declaration", "eng/policy/licence-boundary.json", "Project inventory drift");
        }

        foreach (var row in rows.Where(row => Str(row["kind"]) == "npm"))
        {
            var file = Str(row["path"]) ?? string.Empty;
            var manifest = Obj(ParseJson(c.Text(file)));
            if (manifest is not null && Str(manifest["license"]) != Str(inventory?["spdxLicense"]) && boundaries.GetValueOrDefault(file) == AgplBoundary)
            {
                c.Report("licence-declaration", file, "Manifest licence differs from the inventory");
            }
        }

        var apache = boundaries.Where(entry => entry.Value == ApacheBoundary).Select(entry => entry.Key).Order(StringComparer.Ordinal).ToList();
        if (!apache.SequenceEqual(ApacheBoundaryProjects.Order(StringComparer.Ordinal), StringComparer.Ordinal))
        {
            c.Report("licence-boundary-set", "package.json", "Apache-boundary projects differ from the enumerated list: " + (apache.Count == 0 ? "none" : string.Join(", ", apache)));
        }

        foreach (var file in apache)
        {
            var manifest = Obj(ParseJson(c.Text(file)));
            foreach (var section in ManifestSections)
            {
                foreach (var name in StringMap(manifest?[section]).Keys)
                {
                    if (projectNames.TryGetValue(name, out var target) && boundaries.GetValueOrDefault(target) != ApacheBoundary)
                    {
                        c.Report("licence-cross-boundary", file, "Apache project references AGPL project " + name);
                    }
                }
            }
        }
    }

    /// <summary>The C# projects: a boundary and an expression each, the Apache set, cross-boundary references and the allowlist.</summary>
    private static void ProjectLicences(Context c)
    {
        var declared = c.Projects.Values.Where(p => p.Path.StartsWith("src/", StringComparison.Ordinal) || p.Path.StartsWith("tests/", StringComparison.Ordinal)).ToList();
        foreach (var project in declared)
        {
            if (project.Boundary is null) c.Report("licence-declaration", project.Path, "Project declares no LicenceBoundary");
            if (project.Licence is null) c.Report("licence-declaration", project.Path, "Project declares no PackageLicenseExpression");
            if (project.Boundary == AgplBoundary && project.Licence is not null && project.Licence != "AGPL-3.0-only")
            {
                c.Report("licence-boundary-set", project.Path, "AGPL boundary requires AGPL-3.0-only: " + project.Licence);
            }

            if (project.Boundary == ApacheBoundary && project.Licence is not null && project.Licence != "Apache-2.0")
            {
                c.Report("licence-boundary-set", project.Path, "Apache boundary requires Apache-2.0: " + project.Licence);
            }
        }

        var inventoryText = c.Text("eng/policy/licence-boundary.json");
        var inventory = Obj(ParseJson(inventoryText));
        var msbuildRows = (inventory?["projects"] as JsonArray)?.Select(row => Obj(row)).OfType<JsonObject>()
            .Where(row => Str(row["kind"]) == "msbuild").Select(row => Str(row["path"]) ?? string.Empty).Order(StringComparer.Ordinal).ToList() ?? [];
        var csprojs = c.Projects.Keys.Order(StringComparer.Ordinal).ToList();
        if (!msbuildRows.SequenceEqual(csprojs, StringComparer.Ordinal))
        {
            c.Report("licence-declaration", "eng/policy/licence-boundary.json", "Project inventory drift: msbuild projects");
        }

        var apache = declared.Where(p => p.Boundary == ApacheBoundary).Select(p => p.Path).ToHashSet(StringComparer.Ordinal);
        foreach (var path in apache.Except(ApacheBoundaryProjects, StringComparer.Ordinal))
        {
            c.Report("licence-boundary-set", path, "Apache boundary is not enumerated");
        }

        foreach (var path in ApacheBoundaryProjects.Except(apache, StringComparer.Ordinal))
        {
            c.Report("licence-boundary-set", path, "Enumerated Apache boundary is not declared");
        }

        foreach (var project in declared.Where(p => p.Boundary == ApacheBoundary))
        {
            foreach (var reference in project.ProjectReferences.Where(r => r.Resolved is not null && c.Projects.ContainsKey(r.Resolved)))
            {
                if (c.Projects[reference.Resolved!].Boundary != ApacheBoundary)
                {
                    c.Report("licence-cross-boundary", project.Path, "Apache-boundary project references AGPL project: " + reference.Raw);
                }
            }
        }

        foreach (var project in declared.Where(p => p.Licence is not null))
        {
            var allowed = project.Boundary == ApacheBoundary ? AllowedApache : AllowedAgpl;
            if (project.Path.StartsWith("tests/", StringComparison.Ordinal))
            {
                allowed = new HashSet<string>(allowed.Concat(DevelopmentOnlyLgpl), StringComparer.Ordinal);
            }

            if (SpdxExpression.Allowed(project.Licence, allowed)) continue;
            var development = DevelopmentOnlyLgpl.Any(id => project.Licence!.Contains(id, StringComparison.Ordinal));
            c.Report("licence-allowlist", project.Path, (development && project.Path.StartsWith("src/", StringComparison.Ordinal)
                ? "LGPL is development-only and ships in source: "
                : "Licence is not allowed for the boundary: ") + project.Licence);
        }
    }

    /// <summary>The locked npm closure: every locked licence expression is allowed for the consuming boundary; LGPL only in development.</summary>
    private static void LockLicences(Context c)
    {
        var root = Obj(ParseJson(c.Text("package.json")));
        var apacheRoot = Str(Obj(root?["arcforges"])?["licenceBoundary"]) == ApacheBoundary;
        var lockFile = Obj(ParseJson(c.Text("package-lock.json")));
        if (Obj(lockFile?["packages"]) is not { } packages) return;
        foreach (var (key, value) in packages)
        {
            if (!key.Contains("node_modules/", StringComparison.Ordinal)) continue;
            var item = Obj(value);
            var expression = Str(item?["license"]);
            var developmentOnly = item?["dev"] is JsonValue dev && dev.TryGetValue(out bool devFlag) && devFlag
                || item?["devOptional"] is JsonValue devOptional && devOptional.TryGetValue(out bool devOptionalFlag) && devOptionalFlag;
            var consumer = apacheRoot ? AllowedApache : developmentOnly ? new HashSet<string>(AllowedAgpl.Concat(DevelopmentOnlyLgpl), StringComparer.Ordinal) : AllowedAgpl;
            if (!SpdxExpression.Allowed(expression, consumer))
            {
                c.Report("licence-allowlist", "package-lock.json", key.Split("node_modules/").Last() + ": " + (expression ?? "no licence"));
            }
        }
    }

