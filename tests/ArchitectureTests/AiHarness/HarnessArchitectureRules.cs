    private static Token? Peek(IReadOnlyList<Token> tokens, int index) => index >= 0 && index < tokens.Count ? tokens[index] : null;

    /// <summary>The tokens of a call's argument list, from the opening parenthesis (exclusive) to its matching close.</summary>
    private static List<Token> CallArguments(IReadOnlyList<Token> tokens, int open)
    {
        var depth = 0;
        var found = new List<Token>();
        for (var index = open; index < tokens.Count; index++)
        {
            var token = tokens[index];
            if (token.Kind == TokenKind.Punct && token.Value is "(" or "[" or "{" or "${") depth++;
            else if (token.Kind == TokenKind.Punct && token.Value is ")" or "]" or "}")
            {
                depth--;
                if (depth == 0) break;
            }

            if (index > open) found.Add(token);
        }

        return found;
    }

    /// <summary>A while loop whose condition reads the clock within its first ten tokens: a busy-wait.</summary>
    private static bool ClockBusyWait(IReadOnlyList<Token> tokens, int index)
    {
        var limit = Math.Min(tokens.Count, index + 10);
        for (var position = index; position < limit; position++)
        {
            if (tokens[position].Value == "now" && position > index && tokens[position - 1].Value == ".") return true;
        }

        return false;
    }

    /// <summary>A money identifier whose following tokens (up to a statement end) hold a floating-point literal, an arithmetic helper or a number annotation.</summary>
    private static bool FloatingMoney(IReadOnlyList<Token> tokens, int index)
    {
        var window = new List<Token>();
        for (var cursor = index + 1; cursor < Math.Min(tokens.Count, index + 14); cursor++)
        {
            var item = tokens[cursor];
            if (item.Kind == TokenKind.Punct && item.Value is ";" or "}") break;
            window.Add(item);
        }

        var floating = window.Select((item, offset) => (item, offset)).Any(entry =>
        {
            var (item, offset) = entry;
            if (item.Kind == TokenKind.Number)
            {
                var decimalOrExponent = item.Value.Contains('.') || item.Value.Contains('e') || item.Value.Contains('E');
                return decimalOrExponent && !item.Value.StartsWith("0x", StringComparison.OrdinalIgnoreCase);
            }

            if (item.Kind == TokenKind.Word)
            {
                return item.Value is "parseFloat" or "toFixed" or "toPrecision" or "fround"
                    || (item.Value == "Math" && offset + 1 < window.Count && window[offset + 1].Value == ".");
            }

            return false;
        });
        var annotated = window.Count > 1 && window[0].Value == ":" && window[1].Value == "number";
        var conditional = window.Count > 2 && window[0].Value == "?" && window[1].Value == ":" && window[2].Value == "number";
        return floating || annotated || conditional;
    }

    /// <summary>The identifier parts of a camel or snake case name, lower case, as the AI policy splits them.</summary>
    private static string[] IdentifierParts(string name) =>
        IdentifierBoundary.Replace(name, "$1_$2").ToLowerInvariant().Split(['_', '$'], StringSplitOptions.RemoveEmptyEntries);

    private static bool IsFloating(TypeSyntax type) =>
        type.ToString() is "double" or "float" or "Double" or "Single" or "System.Double" or "System.Single";

    private static bool IsMoney(string identifier) => IdentifierParts(identifier).Any(part => MoneyParts.Contains(part, StringComparer.Ordinal));

    private static string ModuleFolder(string path) => path[..(path.LastIndexOf('/') + 1)];

    /// <summary>True for an expression that can name a task: a call, or a name ending in task.</summary>
    private static bool IsTaskLike(ExpressionSyntax expression) =>
        expression is InvocationExpressionSyntax || expression.ToString().EndsWith("task", StringComparison.OrdinalIgnoreCase);

    private static HashSet<string> RuntimeDependencies(Context c) => StringMap(Obj(ParseJson(c.Text("package.json")))?["dependencies"]).Keys.ToHashSet(StringComparer.Ordinal);

    /// <summary>Every cycle found by a depth-first walk, each as a closed list of nodes.</summary>
    private static List<List<string>> FindCycles(IReadOnlyDictionary<string, List<string>> graph)
    {
        var cycles = new List<List<string>>();
        var state = new Dictionary<string, int>(StringComparer.Ordinal);
        var stack = new List<string>();

        void Visit(string node)
        {
            state[node] = 1;
            stack.Add(node);
            foreach (var next in graph.GetValueOrDefault(node) ?? [])
            {
                if (!state.TryGetValue(next, out var seen))
                {
                    if (graph.ContainsKey(next)) Visit(next);
                }
                else if (seen == 1)
                {
                    var start = stack.IndexOf(next);
                    cycles.Add([.. stack.Skip(start), next]);
                }
            }

            stack.RemoveAt(stack.Count - 1);
            state[node] = 2;
        }

        foreach (var node in graph.Keys.OrderBy(k => k, StringComparer.Ordinal))
        {
            if (!state.ContainsKey(node)) Visit(node);
        }

        return cycles;
    }
