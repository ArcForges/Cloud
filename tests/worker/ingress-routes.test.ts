test("the edge credential check needs a whole Origin match and never reads a cookie as a bearer", () => {
  const request = (headers: Record<string, string>) =>
    new Request("https://x.test/api/a", { method: "POST", headers });
  const cookie = `__Host-af_session=${"A".repeat(43)}`;
  assert.equal(edgeCredentials(request({}), "https://o.test").ok, false);
  assert.equal(
    edgeCredentials(
      request({ cookie, origin: "https://o.test", "x-af-csrf": "B".repeat(43) }),
      "https://o.test",
    ).ok,
    true,
  );
  assert.equal(
    edgeCredentials(
      request({ cookie, origin: "https://o.test", "x-af-csrf": "B".repeat(43) }),
      undefined,
    ).ok,
    false,
  );
  assert.equal(edgeCredentials(request({ authorization: cookie }), "https://o.test").ok, false);
});

test("Paddle ingress keeps the signed bytes and returns only the durable receipt status", async () => {
  assert.ok(paddleWebhookRoute);
  const route = paddleWebhookRoute;
  const path = `https://api.test/api${route.path}`;
  const body = new TextEncoder().encode('{\n  "event_id": "fixture", "display": "测试"\n}');
  const signature = `ts=1700000000;h1=${"a".repeat(64)}`;
  const client = "192.0.2.45";
  const request = (url = path, fields: RequestInit = {}) =>
    new Request(url, {
      method: "POST",
      body,
      headers: {
        "content-type": "application/json; charset=utf-8",
        "paddle-signature": signature,
        "cf-connecting-ip": client,
        authorization: "Bearer unused-browser-credential",
        cookie: "unused=session",
        [clientIpHeader]: "203.0.113.9",
        traceparent: "client-input",
      },
      ...fields,
    });
  const forwarded: Request[] = [];
  const rateKeys: string[] = [];
  let status = 200;
  const env: IngressEnv = {
    SOURCE_REVISION: "fixture",
    ARCFORGES_CENTER_MODE: officialHostedCenterMode,
    FLAGSHIP_SURFACES: "identity,commerce",
    HELLO_RATE_LIMITER: {
      async limit() {
        return { success: true };
      },
    },
    IDENTITY_RATE_LIMITER: {
      async limit({ key }) {
        rateKeys.push(key);
        return { success: true };
      },
    },
    CLOUD_CONTAINER: {
      getByName(name) {
        assert.equal(name, route.instance);
        return {
          async fetch(request) {
            forwarded.push(request);
            return new Response("internal-only", {
              status,
              headers: { "set-cookie": "internal=only", location: "https://unexpected.test" },
            });
          },
        };
      },
    },
  };

  for (const [candidate, settings, expected] of [
    [request(), { ...env, FLAGSHIP_SURFACES: "identity" }, 404],
    [request(), { ...env, ARCFORGES_CENTER_MODE: "self-hosted" }, 404],
    [request(`${path}?opaque`), env, 404],
    [request(`${path}/`), env, 404],
    [request(path, { method: "GET", body: null }), env, 405],
    [request(path, { headers: { "content-type": "application/json" } }), env, 400],
    [
      request(path, {
        headers: { "content-type": "application/json", "content-encoding": "gzip" },
      }),
      env,
      415,
    ],
  ] as const) {
    assert.equal((await handleApiRequest(candidate, settings)).status, expected);
  }
  assert.equal(rateKeys.length, 0);
  assert.equal(forwarded.length, 0);

  const oversized = request(path, { body: new Uint8Array(route.maxRequestBytes + 1) });
  assert.equal((await handleApiRequest(oversized, env)).status, 413);
  assert.equal(forwarded.length, 0);

  const reply = await handleApiRequest(request(), env);
  assert.equal(reply.status, 200);
  assert.equal(reply.headers.has("location"), false);
  assert.equal(reply.headers.has("set-cookie"), false);
  assert.equal(await reply.text(), "");
  assert.ok(rateKeys.every((key) => key === `${route.path}:${client}`));
  assert.equal(forwarded.length, 1);
  const upstream = forwarded[0];
  assert.ok(upstream);
  assert.equal(upstream.url, `http://container${route.path}`);
  assert.equal(upstream.method, route.method);
  assert.equal(upstream.redirect, "manual");
  assert.equal(upstream.headers.get("paddle-signature"), signature);
  assert.equal(upstream.headers.get(clientIpHeader), client);
  assert.match(upstream.headers.get("traceparent") ?? "", /^00-[0-9a-f]{32}-[0-9a-f]{16}-01$/u);
  assert.equal(upstream.headers.has("authorization"), false);
  assert.equal(upstream.headers.has("cookie"), false);
  assert.deepEqual(new Uint8Array(await upstream.arrayBuffer()), body);

  status = 400;
  assert.equal((await handleApiRequest(request(), env)).status, 400);
  status = 302;
  assert.equal((await handleApiRequest(request(), env)).status, 503);
});

test("only fixed typed management routes forward normalized target selection headers", async () => {
  const selected = surfaceRoutes.filter((route) => route.remoteTarget);
  assert.equal(selected.length, 23);
  assert.ok(
    selected.every(
      (route) =>
        route.surface === "nodes" &&
        route.auth === "session" &&
        route.kind === (watchPaths.includes(route.path) ? "serverStream" : "unary"),
    ),
  );
  assert.deepEqual(
    selected.filter((route) => route.kind === "serverStream").map((r) => r.path),
    watchPaths,
  );
  assert.deepEqual(
    selected
      .filter((route) => route.path.startsWith(dataService))
      .map((route) => [
        route.path.slice(dataService.length),
        route.maxRequestBytes,
        route.maxUnaryResponseBytes,
        route.maxDurationMs,
      ]),
    [
      ["BeginImport", 253_952, 1_048_576, 30_000],
      ["WriteImport", 2_097_152, 1_048_576, 30_000],
      ["CommitImport", 253_952, 1_048_576, 30_000],
      ["BeginExport", 253_952, 1_048_576, 30_000],
      ["ReadExport", 253_952, 2_097_152, 30_000],
      ["InspectTransfer", 253_952, 1_048_576, 10_000],
      ["CloseTransfer", 253_952, 1_048_576, 30_000],
    ],
  );
  const forwarded: Request[] = [];
  const env: IngressEnv = {
    SOURCE_REVISION: "worker-route-fixture",
    FLAGSHIP_SURFACES: "identity,pages,fleet,relay,nodes",
    HELLO_RATE_LIMITER: { limit: async () => ({ success: true }) },
    IDENTITY_RATE_LIMITER: { limit: async () => ({ success: true }) },
    CLOUD_CONTAINER: {
      getByName: () => ({
        fetch: async (request) => {
          forwarded.push(request);
          return new Response(null, {
            headers: { "Content-Type": "application/grpc-web+proto", "grpc-status": "0" },
          });
        },
      }),
    },
  };
  const node = "C0000000-0000-0000-0000-000000000001";
  const enrollment = "C0000000-0000-0000-0000-000000000002";
  const grant = "C0000000-0000-0000-0000-000000000003";
  const headers = {
    "content-type": "application/grpc-web+proto",
    "cf-connecting-ip": "203.0.113.10",
    authorization: `Bearer ${"t".repeat(40)}`,
    [remoteNodeHeader]: node,
    [remoteEnrollmentHeader]: enrollment,
    [remoteGrantHeader]: grant,
    [remoteGrantRevisionHeader]: "9223372036854775807",
    "x-arcforges-account-id": node,
    "x-arcforges-actor-id": node,
  };
  const request = (method: string, overrides: Record<string, string> = {}) =>
    new Request(`https://example.test/api${method}`, {
      method: "POST",
      headers: { ...headers, ...overrides },
      body: new Uint8Array([0, 0, 0, 0, 0]),
    });
  const typed = "/arcforges.sandbox.v2.RunService/Start";
  await handleApiRequest(request(typed), env);
  assert.equal(forwarded.length, 1);
  const [routed] = forwarded;
  assert.ok(routed);
  assert.equal(routed.headers.get(remoteNodeHeader), node.toLowerCase());
  assert.equal(routed.headers.get(remoteEnrollmentHeader), enrollment.toLowerCase());
  assert.equal(routed.headers.get(remoteGrantHeader), grant.toLowerCase());
  assert.equal(routed.headers.get(remoteGrantRevisionHeader), "9223372036854775807");
  assert.equal(routed.headers.get("x-arcforges-account-id"), null);
  assert.equal(routed.headers.get("x-arcforges-actor-id"), null);

  for (const invalid of ["0", "01", "+1", "1, 2", "9223372036854775808"])
    await handleApiRequest(request(typed, { [remoteGrantRevisionHeader]: invalid }), env);
  await handleApiRequest(request(typed, { [remoteNodeHeader]: `${node}, ${node}` }), env);
  assert.equal(forwarded.length, 1, "malformed typed target selections never reach the Center");

  await handleApiRequest(request("/arcforges.management.v2.DeviceService/List"), env);
  assert.equal(forwarded.length, 2);
  const [, unrelated] = forwarded;
  assert.ok(unrelated);
  for (const name of [
    remoteNodeHeader,
    remoteEnrollmentHeader,
    remoteGrantHeader,
    remoteGrantRevisionHeader,
  ])
    assert.equal(
      unrelated.headers.get(name),
      null,
      "an unrelated route never forwards target selection",
    );

  for (const path of watchPaths) await handleApiRequest(request(path), env);
  assert.deepEqual(
    forwarded.slice(2).map((call) => new URL(call.url).pathname),
    watchPaths,
  );
  assert.ok(
    forwarded.slice(2).every((call) => call.headers.get(remoteGrantHeader) === grant.toLowerCase()),
  );
});

test("dark and edge-limited watches receive typed terminal errors without waking the Center", async () => {
  const env: IngressEnv = {
    SOURCE_REVISION: "worker-watch-fixture",
    HELLO_RATE_LIMITER: { limit: async () => ({ success: true }) },
    IDENTITY_RATE_LIMITER: { limit: async () => ({ success: false }) },
    CLOUD_CONTAINER: {
      getByName: () => {
        assert.fail("a refused watch must not wake the Center");
      },
    },
  };
  for (const path of watchPaths) {
    for (const [surfaces, code] of [
      ["", "not_activated"],
      ["nodes", "rate_limited"],
    ] as const) {
      const request = new Request(`https://example.test/api${path}`, {
        method: "POST",
        headers: { "content-type": "application/grpc-web+proto" },
      });
      const response = await handleApiRequest(request, { ...env, FLAGSHIP_SURFACES: surfaces });
      const body = Buffer.from(await response.arrayBuffer());
      assert.equal(body[0], 0);
      const framedBytes = 5 + body.readUInt32BE(1);
      const payload = body.subarray(5, framedBytes);
      assert.equal(payload[0], 0x0a, "WatchFrame.ResponseMeta field 1");
      const metaBytes = payload.readUInt8(1);
      assert.equal(payload[metaBytes + 2], 0xa2, "WatchFrame error field 20");
      assert.equal(payload[metaBytes + 3], 0x01);
      assert.ok(payload.includes(code));
      const correlation = payload.subarray(metaBytes - 14, metaBytes + 2);
      assert.ok(correlation.some((byte) => byte !== 0));
      assert.ok(
        payload.subarray(metaBytes + 2).includes(correlation),
        "both layers carry the same ID",
      );
      assert.equal(body[framedBytes], 0x80);
    }
  }
});

// The agreement of this table with the C# host's registrations is no longer a regex over C# sources: the table is generated
// from the registrations (CLOUD.84 S34), and tests/ArcForges.Cloud.Tests/Generation proves the committed table is current.

// ---- deployment configuration: the Container is reachable only through the Worker ----

interface Wrangler {
  workers_dev?: boolean;
  preview_urls?: boolean;
  routes?: { pattern: string; zone_name?: string; custom_domain?: boolean }[];
  containers?: Record<string, unknown>[];
  vars?: Record<string, string>;
  env?: Record<string, Wrangler>;
}

const wrangler = JSON.parse(readFileSync(path.join(root, "wrangler.json"), "utf8")) as Wrangler;

test("production is one Worker route under /api and exposes no other ingress", () => {
  assert.equal(wrangler.workers_dev, false);
  assert.equal(wrangler.preview_urls, false);
  assert.deepEqual(wrangler.routes, [
    { pattern: "arcforges.com/api/*", zone_name: "arcforges.com" },
  ]);
  assert.equal(wrangler.vars?.FOUNDATION_PROOF, undefined);
  assert.equal(wrangler.vars?.ALLOWED_ORIGIN, undefined);
});

test("the proof environment is one custom domain of its own Worker and also keeps every direct URL off", () => {
  const proof = wrangler.env?.proof as Wrangler;
  assert.equal(proof.workers_dev, false);
  assert.equal(proof.preview_urls, false);
  assert.deepEqual(proof.routes, [{ pattern: "proof.arcforges.com", custom_domain: true }]);
});

test("no container declaration publishes a port or an ingress of its own", () => {
  const declarations = [...(wrangler.containers ?? []), ...(wrangler.env?.proof?.containers ?? [])];
  assert.ok(declarations.length >= 2);
  for (const container of declarations)
    assert.deepEqual(Object.keys(container).sort(), [
      "class_name",
      "image",
      "instance_type",
      "max_instances",
    ]);
});

test("the Worker reaches the Container only through its binding, at the private virtual host", () => {
  const ingress = path.join(root, "worker/ingress");
  for (const file of readdirSync(ingress)) {
    const source = readFileSync(path.join(ingress, file), "utf8");
    for (const match of source.matchAll(/https?:\/\/[^"'`\s)]+/gu))
      assert.ok(
        match[0] === "http://container" ||
          /^https?:\/\/\$\{?/u.test(match[0]) ||
          /\.(?:test|example)/u.test(match[0]),
        `${file} names a network location: ${match[0]}`,
      );
    assert.doesNotMatch(
      source,
      /\bfetch\(\s*["'`]https?:/u,
      `${file} calls fetch with a literal URL`,
    );
  }
});
