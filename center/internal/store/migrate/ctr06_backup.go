// The closed non-ACL object inventory is derived from the reviewed 0011
// migrations, not from the archive being admitted. A change to 0011 must
// change this file and its independently reviewed provenance together.
//
//go:embed ctr06_schema11_inventory.txt
var ctr06Schema11Inventory string

//go:embed ctr06_schema10_inventory.txt
var ctr06Schema10Inventory string

const ctr06BackupMetadataVersion = "arcforges-logical-backup-v1"
const ctr06BackupMetadataMax = 8 * 1024 * 1024

// Generated by the native PostgreSQL 18 fresh-migration catalogue probe for
// the supported 0011 schema, and checked again after restoration.
const ctr06Schema11CatalogueSHA = "e2c2583c8e9547bff81ed40d2db0863675218a7cc609edcb505ac60891141074"
const ctr06Schema10CatalogueSHA = "297051199fffd3cedd99888e34634a9f0da07b0acda78b95c6d1808adadaf4a1"

var ctr06SnapshotID = regexp.MustCompile(`^[0-9A-Fa-f-]{1,100}$`)
var ctr06ClusterID = regexp.MustCompile(`^-?(0|[1-9][0-9]*)$`)

type ctr06BackupMigration struct {
	Version int    `json:"version"`
	Name    string `json:"name"`
	SHA256  string `json:"sha256"`
}

type ctr06BackupTable struct {
	Name   string `json:"name"`
	Rows   int64  `json:"rows"`
	SHA256 string `json:"sha256"`
}

type ctr06BackupLargeObject struct {
	OID    uint32 `json:"oid"`
	Bytes  int64  `json:"bytes"`
	SHA256 string `json:"sha256"`
}

type ctr06BackupSequence struct {
	Name     string `json:"name"`
	Value    int64  `json:"value"`
	IsCalled bool   `json:"isCalled"`
}

type ctr06BackupMetadata struct {
	Version               string                   `json:"version"`
	Procedure             string                   `json:"procedure"`
	ArchiveLength         int64                    `json:"archiveLength"`
	ArchiveSHA256         string                   `json:"archiveSha256"`
	ArchiveTOCSHA256      string                   `json:"archiveTocSha256"`
	SourceCluster         string                   `json:"sourceClusterSystemIdentifier"`
	SourceSnapshot        string                   `json:"sourceExportedSnapshot"`
	SourceRuntimeRole     string                   `json:"sourceRuntimeRole"`
	SourceServerMajor     int                      `json:"sourceServerMajor"`
	SourceSchemaVersion   int                      `json:"sourceSchemaVersion"`
	SourceMigrations      []ctr06BackupMigration   `json:"sourceMigrations"`
	SourceCatalogueSHA256 string                   `json:"sourceCatalogueSha256"`
	Tables                []ctr06BackupTable       `json:"tables"`
	Sequences             []ctr06BackupSequence    `json:"sequences"`
	LargeObjects          []ctr06BackupLargeObject `json:"largeObjects"`
}

func ctr06SHA(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

// ctr06ArchiveInventory checks every non-ACL object and multiplicity against
// the supported version, including data entries for empty tables. ACL entries
// are not authority and pg_restore must run with --no-acl; even those entries
// are confined to known schemas and supported object categories.
func ctr06ArchiveInventory(raw []byte, objects []ctr06BackupLargeObject) error {
	return ctr06ArchiveInventoryFor(raw, ctr06Schema11Inventory, objects)
}

func ctr06ArchiveInventoryFor(raw []byte, inventory string, objects []ctr06BackupLargeObject) error {
	if len(raw) == 0 || len(raw) > restoreTOCMax ||
		!strings.Contains(string(raw), "\n;     Format: CUSTOM\n") ||
		!regexp.MustCompile(`(?m)^;     Dumped by pg_dump version: 18[.][0-9]+([^\n]*)$`).Match(raw) {
		return errors.New("archive inventory or custom PostgreSQL 18 format is unsupported")
	}
	expected := make(map[string]int)
	for _, line := range strings.Split(strings.TrimSpace(inventory), "\n") {
		if line == "" || expected[line] != 0 {
			return errors.New("supported archive inventory is malformed")
		}
		expected[line] = 1
	}
	for _, object := range objects {
		if object.OID == 0 {
			return errors.New("large object inventory is invalid")
		}
		for _, prefix := range []string{"BLOB METADATA - ", "BLOBS - "} {
			key := fmt.Sprintf("%s%d", prefix, object.OID)
			if expected[key] != 0 {
				return errors.New("duplicate large object inventory")
			}
			expected[key] = 1
		}
	}
	seenIDs := map[string]bool{}
	seenACL := map[string]bool{}
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	scanner.Buffer(make([]byte, 4096), restoreTOCMax)
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, ";") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 7 || !restoreTOCID.MatchString(fields[0]) || seenIDs[fields[0]] {
			return errors.New("duplicate or ambiguous archive entry")
		}
		seenIDs[fields[0]] = true
		if fields[3] == "ACL" {
			key := strings.Join(fields[4:len(fields)-1], " ")
			if seenACL[key] || !ctr06SupportedACL(fields[4:len(fields)-1], expected) {
				return errors.New("unsupported or duplicate archive ACL entry")
			}
			seenACL[key] = true
			continue
		}
		key := strings.Join(fields[3:len(fields)-1], " ")
		if expected[key] != 1 {
			return errors.New("unsupported or duplicate archive object")
		}
		expected[key] = 0
	}
	if scanner.Err() != nil {
		return errors.New("archive inventory could not be read")
	}
	for _, remaining := range expected {
		if remaining != 0 {
			return errors.New("archive is missing a required object or data entry")
		}
	}
	return nil
}

func ctr06SupportedACL(item []string, objects map[string]int) bool {
	if len(item) == 3 && item[0] == "-" && item[1] == "SCHEMA" {
		_, ok := objects["SCHEMA - "+item[2]]
		return ok
	}
	if len(item) == 3 {
		typ, schemaName, name := item[1], item[0], strings.Trim(item[2], `"`)
		if typ == "TABLE" || typ == "FUNCTION" || typ == "SEQUENCE" {
			_, ok := objects[typ+" "+schemaName+" "+name]
			return ok
		}
	}
	if len(item) == 4 && item[0] == "-" && item[1] == "LARGE" && item[2] == "OBJECT" {
		_, ok := objects["BLOB METADATA - "+item[3]]
		return ok
	}
	return false
}

func ctr06RequiredTables() ([]string, error) {
	return ctr06RequiredTablesFrom(ctr06Schema11Inventory)
}

func ctr06RequiredTablesFrom(inventory string) ([]string, error) {
	var tables []string
	for _, line := range strings.Split(strings.TrimSpace(inventory), "\n") {
		parts := strings.Fields(line)
		if len(parts) == 3 && parts[0] == "TABLE" {
			tables = append(tables, parts[1]+"."+parts[2])
		}
	}
	if len(tables) == 0 {
		return nil, errors.New("supported table inventory is unavailable")
	}
	sort.Strings(tables)
	return tables, nil
}

// JSON duplicate keys are ambiguous even when a decoder would silently keep
// the last value. Check every object before decoding privileged metadata.
func ctr06UniqueJSON(data []byte) error {
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	var value func() error
	value = func() error {
		token, err := decoder.Token()
		if err != nil {
			return err
		}
		delim, composite := token.(json.Delim)
		if !composite {
			return nil
		}
		switch delim {
		case '{':
			keys := map[string]bool{}
			for decoder.More() {
				key, err := decoder.Token()
				name, ok := key.(string)
				if err != nil || !ok || keys[name] {
					return errors.New("duplicate or invalid metadata key")
				}
				keys[name] = true
				if err := value(); err != nil {
					return err
				}
			}
			end, err := decoder.Token()
			if err != nil || end != json.Delim('}') {
				return errors.New("invalid metadata object")
			}
		case '[':
			for decoder.More() {
				if err := value(); err != nil {
					return err
				}
			}
			end, err := decoder.Token()
			if err != nil || end != json.Delim(']') {
				return errors.New("invalid metadata array")
			}
		default:
			return errors.New("invalid metadata delimiter")
		}
		return nil
	}
	if err := value(); err != nil {
		return err
	}
	if _, err := decoder.Token(); err != io.EOF {
		return errors.New("trailing metadata")
	}
	return nil
}

func ctr06ReadMetadata(path, digest string) (ctr06BackupMetadata, error) {
	var meta ctr06BackupMetadata
	if !restoreDigest.MatchString(digest) {
		return meta, errors.New("a metadata SHA-256 is required")
	}
	file, err := os.Open(path)
	if err != nil {
		return meta, errors.New("backup metadata could not be opened")
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > ctr06BackupMetadataMax {
		return meta, errors.New("backup metadata is not a bounded regular file")
	}
	data, err := io.ReadAll(io.LimitReader(file, ctr06BackupMetadataMax+1))
	if err != nil || int64(len(data)) != info.Size() || ctr06SHA(data) != digest {
		return meta, errors.New("backup metadata does not match its expected digest")
	}
	if err := ctr06UniqueJSON(data); err != nil {
		return meta, errors.New("backup metadata is ambiguous")
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&meta); err != nil || decoder.Decode(new(any)) != io.EOF {
		return ctr06BackupMetadata{}, errors.New("backup metadata is malformed")
	}
	return meta, nil
}

func ctr06ValidateMetadata(meta ctr06BackupMetadata, build []Migration) error {
	if meta.Version != ctr06BackupMetadataVersion || meta.Procedure != "checked-full-pg-dump-exported-snapshot-v1" ||
		meta.ArchiveLength <= 0 || !restoreDigest.MatchString(meta.ArchiveSHA256) || !restoreDigest.MatchString(meta.ArchiveTOCSHA256) ||
		!ctr06ClusterID.MatchString(meta.SourceCluster) || !ctr06SnapshotID.MatchString(meta.SourceSnapshot) ||
		meta.SourceServerMajor != TestedMajor || meta.SourceSchemaVersion != 11 || len(meta.SourceMigrations) != 11 ||
		ValidRoleName(meta.SourceRuntimeRole) != nil ||
		len(build) != 11 || meta.SourceCatalogueSHA256 != ctr06Schema11CatalogueSHA {
		return errors.New("unsupported or incomplete trusted backup metadata")
	}
	for i, migration := range meta.SourceMigrations {
		if migration.Version != i+1 || migration.Name != build[i].Name || migration.SHA256 != build[i].SHA256 {
			return errors.New("backup migration checksums do not match the supported schema")
		}
	}
	tables, err := ctr06RequiredTables()
	if err != nil || len(meta.Tables) != len(tables) {
		return errors.New("backup table inventory is incomplete")
	}
	for i, table := range meta.Tables {
		if table.Name != tables[i] || table.Rows < 0 || !restoreDigest.MatchString(table.SHA256) {
			return errors.New("backup table assertions are missing or ambiguous")
		}
	}
	if len(meta.Sequences) != 1 || meta.Sequences[0].Name != "platform.outbox_sequence_seq" {
		return errors.New("backup sequence inventory is incomplete")
	}
	var previous uint32
	for _, object := range meta.LargeObjects {
		if object.OID == 0 || object.OID <= previous || object.Bytes < 0 || !restoreDigest.MatchString(object.SHA256) {
			return errors.New("backup large object inventory is invalid")
		}
		previous = object.OID
	}
	return nil
}

// ctr06SnapshotData hashes each row as a length-framed JSONB representation,
// in a stable order and UTC session. It retains neither row contents nor
// credentials; exact row counts and digests are protected metadata only.
func ctr06SnapshotData(ctx context.Context, q Querier, tables []string) ([]ctr06BackupTable, error) {
	result := make([]ctr06BackupTable, 0, len(tables))
	for _, name := range tables {
		parts := strings.Split(name, ".")
		if len(parts) != 2 {
			return nil, errors.New("unsupported table name")
		}
		quoted := pgx.Identifier{parts[0], parts[1]}.Sanitize()
		rows, err := q.Query(ctx, "SELECT to_jsonb(t)::text FROM "+quoted+" AS t ORDER BY to_jsonb(t)::text COLLATE \"C\"")
		if err != nil {
			return nil, errors.New("a required source or destination table is unreadable")
		}
		digest := sha256.New()
		var count int64
		for rows.Next() {
			var row string
			if err = rows.Scan(&row); err != nil {
				break
			}
			var length [8]byte
			binary.BigEndian.PutUint64(length[:], uint64(len(row)))
			_, _ = digest.Write(length[:])
			_, _ = digest.Write([]byte(row))
			count++
		}
		rows.Close()
		if err != nil || rows.Err() != nil {
			return nil, errors.New("a required source or destination table could not be read completely")
		}
		result = append(result, ctr06BackupTable{Name: name, Rows: count, SHA256: hex.EncodeToString(digest.Sum(nil))})
	}
	return result, nil
}

func ctr06SnapshotLargeObjects(ctx context.Context, q Querier) ([]ctr06BackupLargeObject, error) {
	rows, err := q.Query(ctx, "SELECT oid FROM pg_catalog.pg_largeobject_metadata ORDER BY oid")
	if err != nil {
		return nil, errors.New("the large-object inventory is unavailable")
	}
	var oids []uint32
	for rows.Next() {
		var oid uint32
		if err := rows.Scan(&oid); err != nil {
			rows.Close()
			return nil, errors.New("the large-object inventory is unreadable")
		}
		oids = append(oids, oid)
	}
	rows.Close()
	if rows.Err() != nil {
		return nil, errors.New("the large-object inventory is incomplete")
	}
	result := make([]ctr06BackupLargeObject, 0, len(oids))
	for _, oid := range oids {
		digest := sha256.New()
		var offset int64
		for {
			var chunk []byte
			if err := q.QueryRow(ctx, "SELECT pg_catalog.lo_get($1::oid,$2::bigint,65536)", oid, offset).Scan(&chunk); err != nil {
				return nil, errors.New("a large object is unreadable")
			}
			_, _ = digest.Write(chunk)
			offset += int64(len(chunk))
			if len(chunk) < 65536 {
				break
			}
		}
		result = append(result, ctr06BackupLargeObject{OID: oid, Bytes: offset, SHA256: hex.EncodeToString(digest.Sum(nil))})
	}
	return result, nil
}

func ctr06SnapshotSequences(ctx context.Context, q Querier) ([]ctr06BackupSequence, error) {
	value := ctr06BackupSequence{Name: "platform.outbox_sequence_seq"}
	if err := q.QueryRow(ctx, "SELECT last_value,is_called FROM platform.outbox_sequence_seq").Scan(&value.Value, &value.IsCalled); err != nil {
		return nil, errors.New("the source or destination sequence state is unavailable")
	}
	return []ctr06BackupSequence{value}, nil
}

// A catalogue fingerprint checks definitions in addition to the archive's
// object names. It is taken with search_path=pg_catalog and excludes owner,
// ACLs and OIDs, which must be re-established from the target's own floor.
func ctr06CatalogueSHA(ctx context.Context, q Querier) (string, error) {
	rows, err := q.Query(ctx, `SELECT kind, object, definition FROM (
 SELECT 'table' kind,n.nspname||'.'||c.relname object,
   c.relkind::text||'|'||c.relpersistence::text||'|'||c.relrowsecurity::text||'|'||c.relforcerowsecurity::text definition
 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=ANY($1) AND c.relkind IN ('r','p')
 UNION ALL SELECT 'column',n.nspname||'.'||c.relname||'.'||a.attname,
   pg_catalog.format_type(a.atttypid,a.atttypmod)||'|'||a.attnotnull::text||'|'||a.attidentity::text||'|'||a.attgenerated::text||'|'||coalesce(pg_catalog.pg_get_expr(d.adbin,d.adrelid),'')
 FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_class c ON c.oid=a.attrelid JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
 LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
 WHERE n.nspname=ANY($1) AND c.relkind IN ('r','p') AND a.attnum>0 AND NOT a.attisdropped
 UNION ALL SELECT 'constraint',n.nspname||'.'||c.relname||'.'||x.conname,
   pg_catalog.pg_get_constraintdef(x.oid,true)||'|'||x.convalidated::text||'|'||x.condeferrable::text||'|'||x.condeferred::text
 FROM pg_catalog.pg_constraint x JOIN pg_catalog.pg_class c ON c.oid=x.conrelid JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=ANY($1)
 UNION ALL SELECT 'index',n.nspname||'.'||c.relname,
   pg_catalog.pg_get_indexdef(c.oid)||'|'||i.indisvalid::text||'|'||i.indisready::text||'|'||i.indislive::text
 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace JOIN pg_catalog.pg_index i ON i.indexrelid=c.oid
 WHERE n.nspname=ANY($1) AND c.relkind IN ('i','I')
 UNION ALL SELECT 'function',n.nspname||'.'||p.proname||'('||pg_catalog.pg_get_function_identity_arguments(p.oid)||')',
   pg_catalog.pg_get_functiondef(p.oid)||'|'||p.prosecdef::text||'|'||p.proleakproof::text||'|'||coalesce(p.proconfig::text,'')
 FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname=ANY($1)
 UNION ALL SELECT 'trigger',n.nspname||'.'||c.relname||'.'||t.tgname,
   pg_catalog.pg_get_triggerdef(t.oid,true)||'|'||t.tgenabled::text
 FROM pg_catalog.pg_trigger t JOIN pg_catalog.pg_class c ON c.oid=t.tgrelid JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=ANY($1) AND NOT t.tgisinternal
 UNION ALL SELECT 'sequence',n.nspname||'.'||c.relname,
   format('%s|%s|%s|%s|%s|%s|%s',s.seqtypid::regtype::text,s.seqstart,s.seqincrement,s.seqmin,s.seqmax,s.seqcache,s.seqcycle)
 FROM pg_catalog.pg_sequence s JOIN pg_catalog.pg_class c ON c.oid=s.seqrelid JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=ANY($1)
 ) objects ORDER BY kind COLLATE "C", object COLLATE "C", definition COLLATE "C"`, schema.Schemas)
	if err != nil {
		return "", Sanitize("read the source or destination catalogue", err)
	}
	defer rows.Close()
	digest := sha256.New()
	var count int
	for rows.Next() {
		var kind, object, definition string
		if err := rows.Scan(&kind, &object, &definition); err != nil {
			return "", errors.New("the source or destination catalogue is incomplete")
		}
		for _, value := range []string{kind, object, definition} {
			var length [8]byte
			binary.BigEndian.PutUint64(length[:], uint64(len(value)))
			_, _ = digest.Write(length[:])
			_, _ = digest.Write([]byte(value))
		}
		count++
	}
	if rows.Err() != nil || count == 0 {
		return "", errors.New("the source or destination catalogue is incomplete")
	}
	return hex.EncodeToString(digest.Sum(nil)), nil
}

// The target's own migration owner must own every application schema,
// relation and routine. An archive's historical owner and ACLs are never
// authoritative for the new target.
func ctr06CheckSchemaOwnership(ctx context.Context, q Querier) error {
	var valid bool
	err := q.QueryRow(ctx, `WITH owner AS (SELECT oid FROM pg_roles WHERE rolname=current_user)
 SELECT NOT EXISTS(SELECT 1 FROM pg_namespace n,owner WHERE n.nspname=ANY($1) AND n.nspowner<>owner.oid)
 AND NOT EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace,owner
   WHERE n.nspname=ANY($1) AND c.relowner<>owner.oid)
 AND NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace,owner
   WHERE n.nspname=ANY($1) AND p.proowner<>owner.oid)`, schema.Schemas).Scan(&valid)
	if err != nil || !valid {
		return errors.New("the application schema has an unexpected owner")
	}
	return nil
}

// Archive facts are read from the protected archive itself before any target
// is created. pg_dump sequences are not MVCC rows: bind the actual archived
// SET value separately, rather than claiming it came from the table snapshot.
func ctr06ArchiveFacts(ctx context.Context, tool string, env []string, archive *os.File, build []Migration) ([]ctr06BackupSequence, error) {
	migrationSQL, err := runRestoreTool(ctx, tool, env, archive, "--file=-", "--data-only", "--schema=platform", "--table=schema_migration")
	if err != nil {
		return nil, errors.New("the archived migration history is unreadable")
	}
	const copyHeader = "COPY platform.schema_migration (version, name, sha256, applied_at, applied_by, duration_ms, runner) FROM stdin;"
	inCopy, ended, count := false, false, 0
	for _, line := range strings.Split(string(migrationSQL), "\n") {
		if line == copyHeader {
			if inCopy || ended {
				return nil, errors.New("the archived migration history is ambiguous")
			}
			inCopy = true
			continue
		}
		if !inCopy {
			continue
		}
		if line == `\.` {
			inCopy, ended = false, true
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 7 || count >= len(build) || fields[0] != fmt.Sprint(count+1) || fields[1] != build[count].Name || fields[2] != build[count].SHA256 {
			return nil, errors.New("the archived migration history is incompatible")
		}
		count++
	}
	if inCopy || !ended || count != len(build) {
		return nil, errors.New("the archived migration history is incomplete")
	}
	sequenceSQL, err := runRestoreTool(ctx, tool, env, archive, "--file=-", "--data-only", "--schema=platform", "--table=outbox_sequence_seq")
	if err != nil {
		return nil, errors.New("the archived sequence state is unreadable")
	}
	pattern := regexp.MustCompile(`(?m)^SELECT pg_catalog[.]setval\('platform[.]outbox_sequence_seq', (-?[0-9]+), (true|false)\);$`)
	matches := pattern.FindAllStringSubmatch(string(sequenceSQL), -1)
	if len(matches) != 1 {
		return nil, errors.New("the archived sequence state is missing or ambiguous")
	}
	value, err := strconv.ParseInt(matches[0][1], 10, 64)
	if err != nil {
		return nil, errors.New("the archived sequence value is invalid")
	}
	return []ctr06BackupSequence{{Name: "platform.outbox_sequence_seq", Value: value, IsCalled: matches[0][2] == "true"}}, nil
}

// ctr06VerifyRestoredData checks the actual restored target, including all
// non-protected table rows and history, sequence state and large objects. The
// source floor and admission are retained only in the original backup; the
// target's native protected rows are checked separately before and after.
func ctr06VerifyRestoredData(ctx context.Context, conn *pgx.Conn, meta ctr06BackupMetadata, build []Migration) (string, error) {
	tx, err := conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return "", errors.New("the restored target could not be inspected")
	}
	defer tx.Rollback(context.Background())
	if _, err := tx.Exec(ctx, "SET LOCAL search_path=pg_catalog; SET LOCAL TIME ZONE 'UTC'"); err != nil {
		return "", errors.New("the restored target inspection settings are unavailable")
	}
	applied, exists, err := ReadApplied(ctx, tx)
	if err != nil || !exists || len(applied) != 11 {
		return "", errors.New("the restored migration history is incomplete")
	}
	comparison := Compare(build, applied)
	if len(comparison.Problems) != 0 || len(comparison.Pending) != 0 {
		return "", errors.New("the restored migration history differs from the build")
	}
	if err := ctr06CheckSchemaOwnership(ctx, tx); err != nil {
		return "", err
	}
	catalogue, err := ctr06CatalogueSHA(ctx, tx)
	if err != nil || catalogue != meta.SourceCatalogueSHA256 || catalogue != ctr06Schema11CatalogueSHA {
		return "", errors.New("the restored catalogue does not match the supported source")
	}
	names, err := ctr06RequiredTables()
	if err != nil {
		return "", err
	}
	data, err := ctr06SnapshotData(ctx, tx, names)
	if err != nil || len(data) != len(meta.Tables) {
		return "", errors.New("the restored table data could not be checked")
	}
	for i := range data {
		if data[i].Name == "platform.ctr06_runtime_floor" || data[i].Name == "platform.ctr06_restore_admission" {
			continue
		}
		if data[i] != meta.Tables[i] {
			return "", errors.New("the restored table data does not match the source snapshot")
		}
	}
	sequence, err := ctr06SnapshotSequences(ctx, tx)
	if err != nil || !reflect.DeepEqual(sequence, meta.Sequences) {
		return "", errors.New("the restored sequence does not match the archived state")
	}
	objects, err := ctr06SnapshotLargeObjects(ctx, tx)
	if err != nil || !reflect.DeepEqual(objects, meta.LargeObjects) {
		return "", errors.New("the restored large objects do not match the source snapshot")
	}
	if err := tx.Commit(ctx); err != nil {
		return "", errors.New("the restored target inspection could not complete")
	}
	evidence, err := json.Marshal(meta)
	if err != nil {
		return "", errors.New("the restore verification could not be bound")
	}
	return ctr06SHA(evidence), nil
}
