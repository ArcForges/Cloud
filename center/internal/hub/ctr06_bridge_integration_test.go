// REAL PostgreSQL, ingress, node channel and signed results; the node handler,
// software key and seeded step-up are synthetic. This isolated test exercises
// the bridge's error handling on today's schema with a trigger that produces the
// later migration's precise SQLSTATE/constraint. The separate native-binary
// experiment applies the actual later migration; neither test is Node E2E.
func TestAFCTR06NamespaceBridgeNarrowOnPostgres(t *testing.T) {
	h := routedHarness(t)
	user := h.db.Account(1)
	node := h.enrollIn(user)
	channel := h.connect(node)
	issued := h.accountSession(user, session.ScopeAccount)
	collision, unrelated, normal, task := platform.NewID(), platform.NewID(), platform.NewID(), platform.NewID()
	// IDs are generated by this test and never derived from a request. The
	// error's text is deliberately irrelevant; only SQLSTATE and constraint
	// name are consumed by the product's sanitized mapping.
	h.db.Exec(fmt.Sprintf(`CREATE FUNCTION fleet.test_future_namespace_bridge() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.command_id = '%s'::uuid THEN RAISE EXCEPTION 'test collision' USING ERRCODE='23505', CONSTRAINT='routed_command_id_namespace'; END IF;
 IF NEW.command_id = '%s'::uuid THEN RAISE EXCEPTION 'test collision' USING ERRCODE='23505', CONSTRAINT='other_unique'; END IF;
 RETURN NEW;
END $$`, collision, unrelated), `CREATE TRIGGER test_future_namespace_bridge BEFORE INSERT ON fleet.routed_call FOR EACH ROW EXECUTE FUNCTION fleet.test_future_namespace_bridge()`)
	response := submitResponse(t, task, "bridge")
	calls := serve(t, node, channel, func(call *relayv1.ChannelCall) (*relayv1.ResultHeader, []byte, bool) {
		return node.node.Executed(call, response), response, true
	})
	send := func(command platform.ID) *foundationv1.ArcError {
		h.proveFor(issued, user, "fleet.submitNodeTask", node.node.ID)
		return h.submit(issued.AccessToken, command, node.node.ID, submitPayload(t, command, "bridge")).GetError()
	}
	if failure := send(collision); errorKey(failure) != "CONFLICT/command_id_reused" || failure.GetEffect() != foundationv1.EffectCertainty_EFFECT_CERTAINTY_DID_NOT_HAPPEN {
		t.Fatalf("named conflict: %v", failure)
	}
	if failure := send(unrelated); errorKey(failure) != "INTERNAL/internal" || failure.GetEffect() != foundationv1.EffectCertainty_EFFECT_CERTAINTY_UNKNOWN {
		t.Fatalf("unrelated unique violation changed meaning: %v", failure)
	}
	select {
	case <-calls:
		t.Fatal("refused insert reached the node")
	default:
	}
	for _, command := range []platform.ID{collision, unrelated} {
		record, err := fleet.ReadRouted(context.Background(), h.db.Runtime, user, command)
		if err != nil || record != nil {
			t.Fatalf("refused insert wrote a receipt: %+v %v", record, err)
		}
	}
	if failure := send(normal); failure != nil {
		t.Fatalf("normal old task: %v", failure)
	}
	<-calls
	record, err := fleet.ReadRouted(context.Background(), h.db.Runtime, user, normal)
	if err != nil || record == nil || record.State != fleet.RoutedSucceeded || !record.Final || record.TaskID == nil || *record.TaskID != task {
		t.Fatalf("normal receipt: %+v %v", record, err)
	}
}
