// Path is the generated module, relative to the repository root.
const Path = "worker/tables/center-tables.generated.ts"

const header = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by center/cmd/center-gen from the Go center's registrations (center/internal/routes): the production method table,
// the health route, the switchable surfaces and their method rows, and the transport budgets the Worker applies before it forwards
// a call. The production rows are always on; a surface row is forwarded only while FLAGSHIP_SURFACES names its surface, and is
// otherwise answered with the surface's generated not_activated reply. Do not edit by hand: run
// ` + "`python eng/center.py generate`" + ` and commit the result; the center's Go tests (` + "`python eng/center.py check`" + `) fail on any drift.
// The proof environment's methods and the shared guards and vocabulary stay in cloud-tables.generated.ts, generated from the C#
// host until AF-CTR-09. Nothing here grants anything.

/** The kind of a method the Worker admits: one unary reply, or a server stream. */
export type RouteKind = "unary" | "serverStream";
/** anonymous: no credential is read or forwarded; session: bearer or origin-bound cookie, checked again by the host. */
export type RouteAuth = "anonymous" | "session";

export interface ApiRoute {
  /** The method path without the owned /api prefix: /package.Service/Method. */
  readonly path: string;
  readonly kind: RouteKind;
  readonly auth: RouteAuth;
  /** Bound of the whole request body, frame header included. Unary and server-streaming requests are one message. */
  readonly maxRequestBytes: number;
  /** Bound of one response frame. */
  readonly maxFrameBytes: number;
  /** Bound of a whole unary response (buffered); a stream has no total bound, only its lifetime. */
  readonly maxUnaryResponseBytes: number;
  /** Cap of the RPC deadline (unary) or of the stream's lifetime (server stream). */
  readonly maxDurationMs: number;
  /** The Container instance (Durable Object name) that serves the method. */
  readonly instance: string;
  /**
   * The request message starts with a RequestMeta (field 1, wire registry 04). Only then does the edge read the client's
   * correlation id from it; a method whose field 1 means something else (the Hello name) is never interpreted.
   */
  readonly requestMeta: boolean;
}

/** A switchable surface of the center (AF-CTR-03; AF-PLAT-01 owns the activation variable's other names). */
export type Surface = %SURFACE_TYPE%;

/** A method of a switchable surface. */
export interface SurfaceRoute extends ApiRoute {
  readonly surface: Surface;
}

`

// ErrUnsafeText reports a value that cannot be written as a plain TypeScript string.
var ErrUnsafeText = errors.New("a generated TypeScript string may not contain quotes, backslashes or line breaks")

// Render is the generated module of a production table.
func Render(table routes.WorkerTable) (string, error) {
	var text strings.Builder
	surfaceType := "never"
	if len(table.Surfaces) > 0 {
		quoted := make([]string, len(table.Surfaces))
		for index, surface := range table.Surfaces {
			quoted[index] = quote(surface)
		}
		surfaceType = strings.Join(quoted, " | ")
	}
	text.WriteString(strings.Replace(header, "%SURFACE_TYPE%", surfaceType, 1))
	values := []string{table.HelloPath, table.HealthPath, table.Health.Path, table.Health.Instance}
	for _, row := range append(slices.Clone(table.Production), table.SurfaceRows...) {
		values = append(values, row.Path, row.Instance, row.Surface)
	}
	values = append(values, table.Surfaces...)
	for _, value := range values {
		if strings.ContainsAny(value, "\"\\\n\r") {
			return "", ErrUnsafeText
		}
	}
	// The surfaces come first: the production block (from helloPath to the end) stays byte for byte what the C# generator writes
	// for the rollback host (GeneratedTablesTests.TheGoCenterProductionTableEqualsTheCSharpRegistrations).
	text.WriteString("/** The surface names, in registration order; FLAGSHIP_SURFACES lists them comma-separated and exactly. */\n")
	text.WriteString("export const surfaceNames: readonly Surface[] = [" + joinQuoted(table.Surfaces) + "];\n")
	text.WriteString("/** The header the Worker sets to the client's address (from cf-connecting-ip) on every surface call. */\n")
	text.WriteString("export const clientIpHeader = " + quote(strings.ToLower(config.ClientIPHeader)) + ";\n")
	replies, err := surfaceReplies(table.Surfaces)
	if err != nil {
		return "", err
	}
	text.WriteString("/**\n")
	text.WriteString(" * The gRPC-Web body (one reply frame and the OK status trailer) answering a call of a disabled surface: the domain refusal\n")
	text.WriteString(" * STATE/not_activated naming the surface, without a correlation id (the center's own reply carries one). Base64.\n")
	text.WriteString(" */\n")
	text.WriteString("export const notActivatedReplies: Readonly<Record<Surface, string>> = {\n")
	for _, surface := range table.Surfaces {
		text.WriteString(property(surface, quote(replies[surface])))
	}
	text.WriteString("};\n")
	limited, offsets, err := rateLimitedReply()
	if err != nil {
		return "", err
	}
	text.WriteString("/**\n")
	text.WriteString(" * The gRPC-Web body answering a surface call over the edge rate limit: RESOURCE/rate_limited (limit \"edge\"), retry after time.\n")
	text.WriteString(" * A template: the Worker writes the retry instant (the refusal's time rounded up to the second, plus the edge period) into\n")
	text.WriteString(" * the instant seconds at each offset (retry.retry_at and limit.recovery_at). Base64.\n")
	text.WriteString(" */\n")
	text.WriteString(constant("rateLimitedReply", quote(limited)))
	text.WriteString("/** The byte offsets of the template's instant seconds (zigzag varints of a fixed width). */\n")
	text.WriteString("export const rateLimitedReplyInstantOffsets: readonly number[] = [" + joinInts(offsets) + "];\n")
	text.WriteString("/** The width of each instant's seconds: five varint bytes hold every instant from 1974 to 2514. */\n")
	text.WriteString("export const rateLimitedReplyInstantBytes = " + strconv.Itoa(instantSlotBytes) + ";\n")
	text.WriteString("/** The period of the surface rate limit in seconds (wrangler.json IDENTITY_RATE_LIMITER simple.period). */\n")
	text.WriteString("export const edgeRateLimitPeriodSeconds = " + strconv.Itoa(routes.EdgeRateLimitPeriodSeconds) + ";\n")
	text.WriteString("/** The network that keys an IPv6 client at the edge rate limits; an IPv4 client is keyed by its whole address. */\n")
	text.WriteString("export const edgeIpv6PrefixBits = " + strconv.Itoa(routes.EdgeIPv6PrefixBits) + ";\n")
	text.WriteString("\n")
	text.WriteString("/** The methods of the switchable surfaces; each is forwarded only while its surface is enabled. */\n")
	text.WriteString("export const surfaceRoutes: readonly SurfaceRoute[] = [\n")
	for _, row := range table.SurfaceRows {
		text.WriteString("  {\n")
		route(&text, row, "    ")
		text.WriteString("    surface: " + quote(row.Surface) + ",\n")
		text.WriteString("  },\n")
	}
	text.WriteString("];\n\n")
	text.WriteString("export const helloPath = " + quote(table.HelloPath) + ";\n")
	text.WriteString("export const healthPath = " + quote(table.HealthPath) + ";\n")
	text.WriteString("/** The bound of a whole request body of a method that declares no larger one, frame header included. */\n")
	text.WriteString("export const maxBodyBytes = " + strconv.Itoa(table.MaxBodyBytes) + ";\n")
	text.WriteString("/** The Container may take at most this long to start before a stream's response headers arrive. */\n")
	text.WriteString("export const coldStartBudgetMs = " + strconv.Itoa(table.ColdStartMilliseconds) + ";\n")
	text.WriteString("/** A server stream's lifetime when the client states no shorter deadline: the annex 10 server close after five minutes plus slack. */\n")
	text.WriteString("export const streamLifetimeMs = " + strconv.Itoa(table.StreamLifetimeMilliseconds) + ";\n")
	text.WriteString("\n")
	text.WriteString("/** The health route: a small plain reply that the pipeline answers itself. */\n")
	text.WriteString("export const healthRoute: ApiRoute = {\n")
	route(&text, table.Health, "  ")
	text.WriteString("};\n\n")
	text.WriteString("/** The methods the production Worker serves. */\n")
	text.WriteString("export const productionRoutes: readonly ApiRoute[] = [\n")
	for _, row := range table.Production {
		text.WriteString("  {\n")
		route(&text, row, "    ")
		text.WriteString("  },\n")
	}
	text.WriteString("];\n")
	return text.String(), nil
}

func route(text *strings.Builder, row routes.Row, indent string) {
	text.WriteString(indent + "path: " + quote(row.Path) + ",\n")
	text.WriteString(indent + "kind: " + quote(row.Kind) + ",\n")
	text.WriteString(indent + "auth: " + quote(row.Auth) + ",\n")
	text.WriteString(indent + "maxRequestBytes: " + strconv.Itoa(row.MaxRequestBytes) + ",\n")
	text.WriteString(indent + "maxFrameBytes: " + strconv.Itoa(row.MaxFrameBytes) + ",\n")
	text.WriteString(indent + "maxUnaryResponseBytes: " + strconv.Itoa(row.MaxUnaryResponseBytes) + ",\n")
	text.WriteString(indent + "maxDurationMs: " + strconv.Itoa(row.MaxDurationMilliseconds) + ",\n")
	text.WriteString(indent + "instance: " + quote(row.Instance) + ",\n")
	text.WriteString(indent + "requestMeta: " + strconv.FormatBool(row.RequestMeta) + ",\n")
}

func quote(value string) string { return `"` + value + `"` }

// constant is an exported constant as Prettier lays it out: on one line when it fits the print width of 100, otherwise with the
// value on its own indented line.
func constant(name, value string) string {
	line := "export const " + name + " = " + value + ";\n"
	if len(line)-1 <= 100 {
		return line
	}
	return "export const " + name + " =\n  " + value + ";\n"
}

// property is an object property (two-space indent, trailing comma) as Prettier lays it out: on one line when it fits the print
// width, otherwise with the value on its own line, indented once more.
func property(name, value string) string {
	line := "  " + name + ": " + value + ",\n"
	if len(line)-1 <= 100 {
		return line
	}
	return "  " + name + ":\n    " + value + ",\n"
}

func joinInts(values []int) string {
	texts := make([]string, len(values))
	for index, value := range values {
		texts[index] = strconv.Itoa(value)
	}
	return strings.Join(texts, ", ")
}

func joinQuoted(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = quote(value)
	}
	return strings.Join(quoted, ", ")
}

// grpcWebBody is one reply frame and the OK status trailer frame.
func grpcWebBody(message []byte) string {
	body := append(ingress.Frame(message), ingress.TrailerFrame(ingress.StatusOK, "", false)...)
	return base64.StdEncoding.EncodeToString(body)
}

// surfaceReplies are the generated not_activated replies of the surfaces.
func surfaceReplies(surfaces []string) (map[string]string, error) {
	replies := map[string]string{}
	for _, surface := range surfaces {
		message, err := arc.ReplyMessage(arc.NotActivated(surface).ArcError(correlation.Context{}))
		if err != nil {
			return nil, err
		}
		replies[surface] = grpcWebBody(message)
	}
	return replies, nil
}

// The instant of the rate_limited template: 2^33 seconds (in 2242), whose zigzag (sint64) seconds take five varint bytes, as every
// instant from 1974 (2^27 seconds) to 2514 (2^34 seconds) does, so the Worker writes its instant into the same five bytes.
const (
	instantSlotBytes = 5
	templateSeconds  = int64(1) << 33
)

// rateLimitedReply is the generated reply of the Worker's surface rate limit (PLT-11, F17): RESOURCE/rate_limited, limit "edge",
// retry after time, as a template whose two instants (retry.retry_at and limit.recovery_at, equal as arc.RateLimited makes them) the
// Worker sets at refusal time. It returns the body and the byte offsets of the instants' seconds within it.
func rateLimitedReply() (string, []int, error) {
	message, err := arc.ReplyMessage(arc.RateLimited("edge", 0, time.Unix(templateSeconds, 0)).ArcError(correlation.Context{}))
	if err != nil {
		return "", nil, err
	}
	body, err := base64.StdEncoding.DecodeString(grpcWebBody(message))
	if err != nil {
		return "", nil, err
	}
	// An instant is field 1 (sint64, varint) and field 2 (nanos 0): the tag 0x08, the five seconds bytes, then 0x10 0x00.
	slot := protowire.AppendVarint([]byte{0x08}, protowire.EncodeZigZag(templateSeconds))
	if len(slot) != 1+instantSlotBytes {
		return "", nil, errors.New("the template's instant does not take five varint bytes")
	}
	slot = append(slot, 0x10, 0x00)
	var offsets []int
	for start := 0; ; {
		index := bytes.Index(body[start:], slot)
		if index < 0 {
			break
		}
		offsets = append(offsets, start+index+1)
		start += index + len(slot)
	}
	if len(offsets) != 2 {
		return "", nil, errors.New("the rate_limited template does not hold exactly its two instants")
	}
	return base64.StdEncoding.EncodeToString(body), offsets, nil
}

// Generate renders the table of the center's registrations.
func Generate() (string, error) {
	modules, err := routes.Center()
	if err != nil {
		return "", err
	}
	table, err := routes.Table(modules)
	if err != nil {
		return "", err
	}
	return Render(table)
}

// RepositoryRoot is the repository root above a directory: the first ancestor that holds both center/go.mod and worker/.
func RepositoryRoot(start string) (string, error) {
	directory, err := filepath.Abs(start)
	if err != nil {
		return "", err
	}
	for {
		if exists(filepath.Join(directory, "center", "go.mod")) && exists(filepath.Join(directory, "worker")) {
			return directory, nil
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			return "", errors.New("run inside the Cloud repository")
		}
		directory = parent
	}
}

func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
