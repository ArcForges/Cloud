// Package workertables renders the Worker's production method table, worker/tables/center-tables.generated.ts, from the center's
// registrations (package routes). The layout is the one Prettier keeps unchanged under the repository's settings (print width
// 100, double quotes, trailing commas, two-space indentation), so the file passes the format check without a formatter run, and
// the production rows are byte-for-byte the rows the C# generator wrote before the split (the C# test
// GeneratedTablesTests.TheGoCenterProductionTableEqualsTheCSharpRegistrations checks this).
